val ColorScheme.completedContent: Color
    get() = if (background.luminance() < 0.5f) CompletedGreenDark else CompletedGreenLight

val ColorScheme.completedContainer: Color
    get() = if (background.luminance() < 0.5f) CompletedContainerDark else CompletedContainerLight

@Composable
fun LocationReminderTheme(
    darkTheme: Boolean,
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme

    MaterialTheme(
        colorScheme = colorScheme,
        content = content
    )
}